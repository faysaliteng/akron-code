// Live verification of the REAL composer flow (no direct IPC): type a request,
// press Send, and watch the in-progress UI + the generated site + the per-chat
// project folder. Uses a stub OpenAI-compatible provider (streaming SSE, slow
// enough to observe the "working" UI) so it costs no tokens.
'use strict';
const http = require('http');
const fs = require('fs');
const path = require('path');
const WebSocket = require('ws');

const PORT = 8900;
const PAGE_HTML = `<!doctype html>
<html><head><meta charset="utf-8"><title>Helio Live Scores</title>
<style>body{font-family:system-ui;background:#080d1a;color:#e9eefc;margin:0;padding:36px}
h1{font-weight:800;letter-spacing:-1px}.row{display:flex;gap:14px;align-items:center;font-size:28px}
.badge{background:#16a34a;color:#fff;font-size:12px;padding:3px 8px;border-radius:99px}
.score{font-size:56px;font-weight:900;color:#5eead4}</style></head>
<body><h1>Premier League</h1>
<div class="row"><span class="badge">LIVE 78'</span><span class="score">ARS 2 — 1 CHE</span></div>
<p>Generated by Helio Bot inside this conversation's project folder.</p></body></html>`;
const FINAL_TEXT =
  'Done — the live score page is written to your project folder and opened in the browser pane. ' +
  'You can keep iterating on it: ask for more matches, a different league, or auto-refresh.';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function sseHead(res) {
  res.writeHead(200, {
    'content-type': 'text/event-stream; charset=utf-8',
    'cache-control': 'no-cache',
    connection: 'keep-alive',
  });
}
function writeSse(res, obj) {
  res.write('data: ' + JSON.stringify(obj) + '\n\n');
}

async function streamToolCall(res) {
  // Real models narrate before they act. Emitting text -> tool -> text is what
  // used to collapse into one glued paragraph, so the stub reproduces it.
  sseHead(res);
  writeSse(res, { choices: [{ index: 0, delta: { role: 'assistant', content: '' } }] });
  // Reasoning models (DeepSeek/Kimi) stream chain-of-thought first. Claude shows
  // that as a collapsible block in the transcript, so verify it renders there.
  for (const think of ['The user wants a live score page. ', 'I will write one self-contained index.html.']) {
    writeSse(res, { choices: [{ index: 0, delta: { reasoning_content: think } }] });
    await sleep(70);
  }
  for (const chunk of ['Let me build ', 'that page ', 'for you.']) {
    writeSse(res, { choices: [{ index: 0, delta: { content: chunk } }] });
    await sleep(90);
  }
  await sleep(150);
  writeSse(res, {
    choices: [{ index: 0, delta: { tool_calls: [{ index: 0, id: 'call_1', type: 'function', function: { name: 'Write', arguments: '' } }] } }],
  });
  await sleep(450);
  const args = JSON.stringify({ file_path: 'index.html', content: PAGE_HTML });
  const step = Math.ceil(args.length / 5);
  for (let i = 0; i < args.length; i += step) {
    writeSse(res, { choices: [{ index: 0, delta: { tool_calls: [{ index: 0, function: { arguments: args.slice(i, i + step) } }] } }] });
    await sleep(260);
  }
  writeSse(res, { choices: [{ index: 0, delta: {}, finish_reason: 'tool_calls' }] });
  res.write('data: [DONE]\n\n');
  res.end();
}

async function streamText(res, text) {
  sseHead(res);
  writeSse(res, { choices: [{ index: 0, delta: { role: 'assistant', content: '' } }] });
  const step = 14;
  for (let i = 0; i < text.length; i += step) {
    writeSse(res, { choices: [{ index: 0, delta: { content: text.slice(i, i + step) } }] });
    await sleep(70);
  }
  writeSse(res, { choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] });
  res.write('data: [DONE]\n\n');
  res.end();
}

const seen = [];
const server = http.createServer((req, res) => {
  let raw = '';
  req.on('data', (c) => (raw += c));
  req.on('end', async () => {
    let body = {};
    try { body = JSON.parse(raw || '{}'); } catch (_) {}
    const msgs = body.messages || [];
    const sawResult = msgs.some((m) => m.role === 'tool' || (m.role === 'user' && /^TOOL RESULT/.test(String(m.content || ''))));
    const askedForSite = msgs.some((m) => m.role === 'user' && /football|score website|live score/i.test(String(m.content || '')));
    seen.push({ stream: !!body.stream, msgs: msgs.length, sawResult, askedForSite, tools: (body.tools || []).length });
    if (body.stream && sawResult) return streamText(res, FINAL_TEXT);
    if (body.stream && askedForSite) return streamToolCall(res);
    // Probe / title / anything else: a tiny non-streaming reply.
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ choices: [{ index: 0, finish_reason: 'stop', message: { role: 'assistant', content: 'Okay.' } }] }));
  });
});

function rpc(ws, method, params) {
  return new Promise((resolve, reject) => {
    const id = Math.floor(Math.random() * 1e9);
    const onMsg = (raw) => {
      let m; try { m = JSON.parse(raw); } catch { return; }
      if (m.id !== id) return;
      ws.off('message', onMsg);
      if (m.error) return reject(new Error(JSON.stringify(m.error)));
      resolve(m.result);
    };
    ws.on('message', onMsg);
    ws.send(JSON.stringify({ id, method, params }));
  });
}

async function evaluate(ws, expression) {
  const r = await rpc(ws, 'Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true, userGesture: true });
  const res = r.result || {};
  if (res.subtype === 'error') throw new Error(res.description || 'eval error');
  return res.value !== undefined ? res.value : res.description;
}

(async () => {
  await new Promise((r) => server.listen(PORT, '127.0.0.1', r));
  const list = JSON.parse(await new Promise((resolve, reject) => {
    http.get('http://127.0.0.1:9333/json/list', (res) => { let s = ''; res.on('data', (d) => (s += d)); res.on('end', () => resolve(s)); }).on('error', reject);
  }));
  const page = list.find((t) => t.type === 'page' && /Helio Bot|index\.html/.test(t.title + t.url));
  if (!page) throw new Error('no page target: ' + JSON.stringify(list.map((t) => t.type + ':' + t.title)));
  const ws = new WebSocket(page.webSocketDebuggerUrl, { perMessageDeflate: false });
  await new Promise((r, j) => { ws.on('open', r); ws.on('error', j); });

  // Point the app at the stub provider and start from a fresh chat.
  await evaluate(ws, `(() => {
    localStorage.setItem('autobot:provider', JSON.stringify({
      baseURL: 'http://127.0.0.1:${PORT}/v1', apiKey: 'stub', model: 'stub-model', name: 'Stub',
      supportsTools: true, reasoningLevel: 'auto'
    }));
    localStorage.setItem('autobot:activeId', 'null');
    localStorage.setItem('autobot:convs', '[]');
    const keys = Object.keys(localStorage).filter((k) => k.startsWith('autobot:workspace:'));
    keys.forEach((k) => localStorage.removeItem(k));
    return keys.length;
  })()`);
  await rpc(ws, 'Page.reload', {});
  await sleep(2500);

  // Type into the composer and send (React-aware value set + input event).
  const sent = await evaluate(ws, `(() => {
    const ta = document.querySelector('.composer textarea') || document.querySelector('textarea');
    if (!ta) return 'no-composer';
    const set = Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, 'value').set;
    set.call(ta, 'build me a live football score website');
    ta.dispatchEvent(new Event('input', { bubbles: true }));
    const btn = document.querySelector('button.send:not(.stop)');
    if (!btn) return 'no-send-button';
    btn.click();
    return 'sent';
  })()`);
  console.log('composer:', sent);

  // Sample the in-progress UI while the run is live.
  const samples = [];
  for (let i = 0; i < 120; i++) {
    await sleep(250);
    const s = await evaluate(ws, `(() => {
      const act = document.querySelector('.activity');
      const cwdEl = document.querySelector('.cwdbar .cwd');
      const cards = Array.from(document.querySelectorAll('.toolcard')).map((c) => c.innerText.replace(/\\s+/g, ' ').trim());
      const stop = !!document.querySelector('button.send.stop');
      return JSON.stringify({
        streaming: stop,
        activity: act ? act.innerText.replace(/\\s+/g, ' ').trim() : null,
        cards,
        cwd: cwdEl ? cwdEl.innerText.replace(/\\s+/g, ' ').trim() : null,
        msgs: document.querySelectorAll('.msg').length,
        workedFor: (document.querySelector('.worked-for') || {}).innerText || null,
      });
    })()`);
    samples.push(JSON.parse(s));
    const last = samples[samples.length - 1];
    if (!last.streaming && last.workedFor) break;
  }
  const liveSeen = samples.filter((x) => x.streaming);
  const firstCwd = (liveSeen.find((x) => x.cwd) || samples.find((x) => x.cwd) || {}).cwd;

  await sleep(2000);
  const final = JSON.parse(await evaluate(ws, `(() => {
    const wv = Array.from(document.querySelectorAll('webview')).map((w) => {
      let url = null, title = null;
      try { url = w.getURL(); } catch (_) {}
      try { title = w.getTitle ? w.getTitle() : null; } catch (_) {}
      return { url, title };
    });
    const tabs = Array.from(document.querySelectorAll('.browser-tabs .btab, .browser-tabs [class*=tab]')).map((t) => t.innerText.trim()).filter(Boolean);
    const texts = Array.from(document.querySelectorAll('.md')).map((t) => t.innerText.replace(/\\s+/g, ' ').trim()).filter(Boolean);
    const lastMsg = Array.from(document.querySelectorAll('.msg.assistant')).pop();
    const blocks = lastMsg ? Array.from(lastMsg.querySelectorAll('.md, .toolcard, .thinkblock')).map((e) => (
      e.classList.contains('toolcard')
        ? 'tool:' + e.innerText.replace(/\\s+/g, ' ').trim()
        : e.classList.contains('thinkblock')
          ? 'think:' + e.innerText.replace(/\\s+/g, ' ').trim().slice(0, 60)
          : 'text:' + e.innerText.replace(/\\s+/g, ' ').trim().slice(0, 60)
    )) : [];
    const convTitles = Array.from(document.querySelectorAll('.conv .conv-title')).map((t) => t.innerText.trim()).slice(0, 5);
    return JSON.stringify({ wv, tabs, texts: texts.slice(-4), blocks, convTitles, workedFor: (document.querySelector('.worked-for') || {}).innerText || null });
  })()`));

  const shot = (await rpc(ws, 'Page.captureScreenshot', { format: 'png' })).data;
  const shotPath = path.join(__dirname, '..', '..', 'screenshots', 'composer-flow.png');
  fs.mkdirSync(path.dirname(shotPath), { recursive: true });
  fs.writeFileSync(shotPath, Buffer.from(shot, 'base64'));

  const report = {
    composer: sent,
    requests: seen,
    liveSamples: liveSeen.length,
    activitySeen: [...new Set(liveSeen.map((x) => x.activity).filter(Boolean))].slice(0, 6),
    toolRows: [...new Set(samples.flatMap((x) => x.cards))].slice(0, 6),
    cwdDuringLive: firstCwd,
    final,
    screenshot: shotPath,
  };
  console.log(JSON.stringify(report, null, 2));

  const dir = String(firstCwd || '').replace(/^\s*/, '').replace(/^.*?(~?\/|^)(?=[A-Za-z])/, (m) => m);
  const guess = (String(firstCwd || '').match(/\/Users\/[^\n]+/) || [])[0];
  if (guess && fs.existsSync(guess)) console.log('disk:', guess, fs.readdirSync(guess));

  // Ordering is the thing the user sees: reasoning, then narration, then the tool
  // it triggered, then the follow-up — each its own block, never one blob.
  const blocks = (final && final.blocks) || [];
  const shape = blocks.map((b) => b.split(':')[0]).join('>');
  const okShape = /think>text>tool>text/.test(shape);
  const webviewOk = ((final && final.wv) || []).some((w) => /\.html?$/i.test(String(w.url || '')));
  const diskOk = !!(guess && fs.existsSync(guess + '/index.html'));
  console.log('blockOrder:', shape);
  const pass = sent === 'sent' && liveSeen.length > 0 && okShape && webviewOk && diskOk;
  console.log(pass ? '\nPASS: composer run → live activity → ordered transcript → page in pane + on disk' : '\nFAIL: see report');
  ws.close();
  server.close();
  process.exit(pass ? 0 : 1);
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
