// Live verification of the "generated website actually shows up" pipeline.
//
// Drives the REAL app over CDP: a stub OpenAI-compatible endpoint returns a
// single `Write` tool call, so the whole chain is exercised without a real
// model — llm.js runAgent → tools.runTool (file on disk) → `preview` event →
// renderer openPreview → BrowserView <webview> loads the file:// URL.
'use strict';
const http = require('http');
const fs = require('fs');
const path = require('path');
const WebSocket = require('ws');

const PORT = Number(process.env.STUB_PORT || 8899);
const DIR = '/Users/saimon/Helio Bot/live-preview-test';
const PAGE_HTML = `<!doctype html>
<html><head><meta charset="utf-8"><title>Live Scores</title>
<style>body{font-family:system-ui;background:#0b1020;color:#e8eefc;padding:40px}
.score{font-size:64px;font-weight:800;color:#5eead4}</style></head>
<body><h1>Premier League — Live</h1><div class="score" id="s">ARS 2 - 1 CHE</div>
<p>Updated just now. This page was generated by the app.</p>
<script>setTimeout(()=>{document.getElementById('s').textContent='ARS 2 - 1 CHE · 78\\''},800)</script>
</body></html>`;

// ---- stub provider -------------------------------------------------------
let calls = 0;
const server = http.createServer((req, res) => {
  let body = '';
  req.on('data', (c) => (body += c));
  req.on('end', () => {
    calls += 1;
    let out;
    if (calls === 1) {
      out = {
        choices: [{
          index: 0,
          finish_reason: 'tool_calls',
          message: {
            role: 'assistant',
            content: '',
            tool_calls: [{
              id: 'call_live_1',
              type: 'function',
              function: {
                name: 'Write',
                arguments: JSON.stringify({ file_path: 'index.html', content: PAGE_HTML }),
              },
            }],
          },
        }],
      };
    } else {
      out = {
        choices: [{
          index: 0,
          finish_reason: 'stop',
          message: { role: 'assistant', content: 'Built the live score page — it is open in the browser pane.' },
        }],
      };
    }
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify(out));
  });
});

// ---- tiny CDP client -----------------------------------------------------
async function evaluate(ws, expression) {
  return new Promise((resolve, reject) => {
    const id = Math.floor(Math.random() * 1e9);
    const onMsg = (raw) => {
      let m;
      try { m = JSON.parse(raw); } catch { return; }
      if (m.id !== id) return;
      ws.off('message', onMsg);
      if (m.error) return reject(new Error(JSON.stringify(m.error)));
      const r = m.result?.result || {};
      if (r.subtype === 'error') return reject(new Error(r.description || 'eval error'));
      resolve(r.value !== undefined ? r.value : r.description);
    };
    ws.on('message', onMsg);
    ws.send(JSON.stringify({
      id,
      method: 'Runtime.evaluate',
      params: { expression, awaitPromise: true, returnByValue: true, userGesture: true },
    }));
  });
}

(async () => {
  fs.mkdirSync(DIR, { recursive: true });
  await new Promise((r) => server.listen(PORT, '127.0.0.1', r));

  const targets = JSON.parse(await new Promise((resolve, reject) => {
    http.get('http://127.0.0.1:9333/json/list', (res) => {
      let s = ''; res.on('data', (d) => (s += d)); res.on('end', () => resolve(s));
    }).on('error', reject);
  }));
  const page = targets.find((t) => t.type === 'page' && /Helio Bot|index\.html/.test(t.title + t.url));
  if (!page) throw new Error('Helio Bot page target not found');

  const ws = new WebSocket(page.webSocketDebuggerUrl, { perMessageDeflate: false });
  await new Promise((r, j) => { ws.on('open', r); ws.on('error', j); });

  const script = `(async () => {
    const events = [];
    const detail = [];
    const off = window.autobot.onEvent((e) => {
      events.push(e.type + (e.url ? ' -> ' + e.url : '') + (e.tool ? ' [' + e.tool + ']' : '') + (e.text ? ' ' + String(e.text).slice(0, 120) : ''));
      if (e.type === 'toolResult') detail.push({ tool: e.name, content: String(e.content || '').slice(0, 200), isError: !!e.isError });
      if (e.type === 'tool') detail.push({ call: e.name, args: JSON.stringify(e.args || {}).slice(0, 160) });
    });
    const t0 = Date.now();
    let runErr = null;
    try {
      await window.autobot.run({
        runId: 'livetest-' + Date.now(),
        messages: [{ role: 'user', content: 'build a live score page' }],
        provider: { baseURL: 'http://127.0.0.1:${PORT}/v1', apiKey: 'stub', model: 'stub', supportsTools: true },
        cwd: ${JSON.stringify(DIR)},
        convId: 'livetest',
        permissions: 'auto',
        maxSteps: 4,
        useMemory: false,
      });
    } catch (e) { runErr = String(e && e.message || e); }
    await new Promise((r) => setTimeout(r, 3000));
    off && off();
    const wv = Array.from(document.querySelectorAll('webview')).map((w) => {
      let url = null;
      try { url = w.getURL(); } catch (_) {}
      return { src: w.getAttribute('src'), url };
    });
    const tabs = Array.from(document.querySelectorAll('.browser-tabs *')).map((n) => n.textContent.trim()).filter(Boolean).slice(0, 12);
    const paneOpen = !!document.querySelector('.browser-panel');
    return JSON.stringify({ runErr, elapsedMs: Date.now() - t0, events, detail, paneOpen, wv, tabs });
  })()`;

  const raw = await evaluate(ws, script);
  const out = JSON.parse(raw);
  console.log(JSON.stringify(out, null, 2));
  console.log('--- disk ---');
  console.log(DIR, fs.readdirSync(DIR));

  // Screenshot the whole window for the visual check.
  const shot = await new Promise((resolve, reject) => {
    const id = 4242;
    const onMsg = (m) => {
      const j = JSON.parse(m);
      if (j.id !== id) return;
      ws.off('message', onMsg);
      if (j.error) return reject(new Error(JSON.stringify(j.error)));
      resolve(j.result.data);
    };
    ws.on('message', onMsg);
    ws.send(JSON.stringify({ id, method: 'Page.captureScreenshot', params: { format: 'png' } }));
  });
  const shotPath = path.join(__dirname, '..', '..', 'screenshots', 'preview-pipeline.png');
  fs.mkdirSync(path.dirname(shotPath), { recursive: true });
  fs.writeFileSync(shotPath, Buffer.from(shot, 'base64'));
  console.log('screenshot:', shotPath);

  ws.close();
  server.close();
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
