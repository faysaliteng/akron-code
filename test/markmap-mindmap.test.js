'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const mindmap = require(path.join(ROOT, 'electron', 'mindmap'));

const tests = [];
function test(name, fn) {
  tests.push({ name, fn });
}

test('electron/mindmap.js renders Akron Code attribution (no Akron Bot) & builds workspace markdown', () => {
  const mmSrc = fs.readFileSync(path.join(ROOT, 'electron', 'mindmap.js'), 'utf8');
  assert.ok(mmSrc.includes('auto-generated by Akron Code'));
  assert.ok(!mmSrc.includes('auto-generated by Akron Bot'));

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'akron-mm-'));
  try {
    fs.mkdirSync(path.join(tmp, 'src'), { recursive: true });
    fs.writeFileSync(path.join(tmp, 'src', 'index.js'), 'export const hi = 1;\n');
    const md = mindmap.buildWorkspaceMarkdown(tmp, 'tree');
    assert.ok(md.includes('## Files'));
    assert.ok(md.includes('src/index.js'));
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});

test('MindMapView uses offline markmap-lib + markmap-view with zero CDN scripts & file-click handler', () => {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  assert.ok(pkg.dependencies['markmap-lib'], 'markmap-lib must be bundled in dependencies');
  assert.ok(pkg.dependencies['markmap-view'], 'markmap-view must be bundled in dependencies');

  const viewSrc = fs.readFileSync(path.join(ROOT, 'src', 'ide', 'MindMapView.jsx'), 'utf8');
  assert.ok(viewSrc.includes("from 'markmap-lib'"));
  assert.ok(viewSrc.includes("from 'markmap-view'"));
  assert.ok(!/cdn\.jsdelivr|unpkg\.com|cdnjs/i.test(viewSrc), 'Must be 100% offline with zero CDN links');
  assert.ok(viewSrc.includes('onOpenFile'));
  assert.ok(viewSrc.includes('akron-mindmap.svg'));
});

test('autobot:getMindmap IPC & UI entrypoints are wired across main, preload, IDE, and App', () => {
  const mainSrc = fs.readFileSync(path.join(ROOT, 'electron', 'main.js'), 'utf8');
  const preloadSrc = fs.readFileSync(path.join(ROOT, 'electron', 'preload.js'), 'utf8');
  const ideSrc = fs.readFileSync(path.join(ROOT, 'src', 'ide', 'IdeWorkbench.jsx'), 'utf8');
  const appSrc = fs.readFileSync(path.join(ROOT, 'src', 'App.jsx'), 'utf8');

  assert.ok(mainSrc.includes('autobot:getMindmap'));
  assert.ok(preloadSrc.includes('getMindmap'));
  assert.ok(ideSrc.includes('MindMapView'));
  assert.ok(appSrc.includes('MindMapView'));
});

(async () => {
  let pass = 0;
  let fail = 0;
  console.log('\nMarkmap Interactive Mind Map Verification');
  for (const t of tests) {
    try {
      await t.fn();
      pass++;
      console.log('  ok   - ' + t.name);
    } catch (e) {
      fail++;
      console.error('  FAIL - ' + t.name + ': ' + (e && e.stack ? e.stack : e));
    }
  }
  console.log(`\nSummary: ${pass}/${tests.length} passed`);
  if (fail) process.exit(1);
})();
