'use strict';
for (const m of ['memory', 'permissions', 'commands', 'checkpoints', 'agentdefs', 'claudeconfig']) require('../electron/' + m);
require('../electron/llm.js');
const perms = require('../electron/permissions');
const assert = require('assert');
assert.strictEqual(perms.matchBash('git diff:*', 'git diff'), true);
assert.strictEqual(perms.matchBash('git diff:*', 'git diff --stat'), true);
assert.strictEqual(perms.matchBash('rm:*', 'ls -la'), false);
assert.strictEqual(perms.matchGlob('src/**', 'src/a/b.js'), true);
assert.strictEqual(perms.matchGlob('src/**', 'lib/c.js'), false);
assert.strictEqual(perms.matchGlob('**/*.env', '/home/u/app/.env'), true);
const p = perms.decide({ allow: ['Bash(git diff:*)'], deny: ['Bash(rm:*)'], ask: [] }, 'Bash', { command: 'git diff HEAD' }, { mode: 'manual' });
assert.strictEqual(p.decision, 'allow');
const d = perms.decide({ allow: [], deny: ['Bash(rm:*)'], ask: [] }, 'Bash', { command: 'rm -rf x' }, { mode: 'bypass' });
assert.strictEqual(d.decision, 'deny');
const a = perms.decide({ allow: [], deny: [], ask: ['Bash(git push:*)'] }, 'Bash', { command: 'git push origin' }, { mode: 'auto' });
assert.strictEqual(a.decision, 'ask');
const cmds = require('../electron/commands');
console.log('BUILTIN', cmds.BUILTIN.length, 'cmdDirs', cmds.commandDirs(process.cwd()).length);
const mem = require('../electron/memory');
console.log('memoryFiles', mem.memoryFiles(process.cwd()).length);
const defs = require('../electron/agentdefs');
console.log('agentdefs', defs.discover(process.cwd()).map(x => x.name).join(','));
console.log('OK');
