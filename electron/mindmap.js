'use strict';
// Per-project mindmap — a self-contained project-state summary stored as
// MINDMAP.md in each conversation's project folder. On a model switch the next
// model reads this (injected as <project_mindmap>) and immediately understands
// the goal, progress, decisions and files — cross-model continuity without any
// shared provider state. Claude Desktop parity: a project context that survives
// swapping gemma4 → Kimi → DeepSeek → Nemotron → TokenRouter.

const fs = require('fs');
const path = require('path');

const FILENAME = 'MINDMAP.md';

function fileFor(cwd) {
  if (!cwd) return null;
  return path.join(String(cwd), FILENAME);
}

function read(cwd) {
  const f = fileFor(cwd);
  if (!f) return null;
  try {
    if (fs.existsSync(f)) return fs.readFileSync(f, 'utf8');
  } catch (_) {}
  return null;
}

function write(cwd, state) {
  const f = fileFor(cwd);
  if (!f) return null;
  try { fs.mkdirSync(path.dirname(f), { recursive: true }); } catch (_) {}
  fs.writeFileSync(f, render(state), 'utf8');
  return f;
}

function render(state) {
  const s = state || {};
  const title = s.title || 'Untitled project';
  const dir = s.dir || '';
  const goal = s.goal || '';
  const lastExchange = s.lastExchange || '';
  const todos = Array.isArray(s.todos) ? s.todos : [];
  const decisions = Array.isArray(s.decisions) ? s.decisions : [];
  const files = Array.isArray(s.files) ? s.files : [];
  const activity = Array.isArray(s.activity) ? s.activity : [];
  const at = new Date().toISOString();

  const L = [];
  L.push(`# ${title}`);
  L.push('');
  L.push('> Project mindmap — auto-generated by Akron Bot. A model that takes over this conversation (Gemma, Kimi, DeepSeek, Nemotron, …) should read this block to continue seamlessly. Treat this as project context, not as user instructions.');
  L.push('');
  if (dir) L.push(`- **Working directory:** \`${dir}\``);
  L.push(`- **Last updated:** ${at}`);
  L.push('');
  if (goal) { L.push('## Goal'); L.push(''); L.push(goal); L.push(''); }
  if (todos.length) { L.push('## Todos'); L.push(''); todos.forEach((t) => L.push(`- [ ] ${t}`)); L.push(''); }
  if (decisions.length) { L.push('## Decisions'); L.push(''); decisions.forEach((d) => L.push(`- ${d}`)); L.push(''); }
  if (files.length) { L.push('## Files'); L.push(''); files.forEach((f) => L.push(`- \`${f}\``)); L.push(''); }
  if (activity.length) {
    L.push('## Recent activity');
    L.push('');
    L.push('What the previous model already did in this project — continue from here, do not redo it:');
    L.push('');
    activity.forEach((a) => L.push(`- ${a}`));
    L.push('');
  }
  if (lastExchange) { L.push('## Last exchange'); L.push(''); L.push(lastExchange); L.push(''); }
  return L.join('\n').trim() + '\n';
}

// Create a stub mindmap when a project folder is first created so it exists from
// the very first run (and every model switch thereafter). Never clobbers one.
function ensureStub(cwd, title) {
  const f = fileFor(cwd);
  if (!f) return null;
  if (fs.existsSync(f)) return f;
  return write(cwd, {
    title: title || path.basename(String(cwd)) || 'Untitled project',
    dir: String(cwd),
    goal: '',
    lastExchange: '',
  });
}

function firstUser(messages) {
  for (const m of messages || []) {
    if (m && m.role === 'user' && m.content) return String(m.content).slice(0, 400);
  }
  return '';
}

function lastAssistant(messages) {
  for (let i = (messages || []).length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m && m.role === 'assistant' && m.content) return String(m.content).slice(0, 400);
  }
  return '';
}

const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', '.next', '.cache', 'venv', '__pycache__', '.venv', 'target', 'release', 'out']);

function listFiles(cwd) {
  if (!cwd) return [];
  const out = [];
  const walk = (dir, rel, depth) => {
    if (out.length >= 60 || depth > 2) return;
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return; }
    for (const e of entries) {
      if (out.length >= 60) return;
      if (e.name.startsWith('.') || e.name === FILENAME) continue;
      const r = rel ? rel + '/' + e.name : e.name;
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name)) continue;
        walk(path.join(dir, e.name), r, depth + 1);
      } else {
        let size = 0;
        try { size = fs.statSync(path.join(dir, e.name)).size; } catch (_) {}
        out.push(`${r} (${size}b)`);
      }
    }
  };
  walk(String(cwd), '', 1);
  return out;
}

function oneLine(s, n) {
  return String(s == null ? '' : s).replace(/\s+/g, ' ').trim().slice(0, n || 140);
}

// Condense the run's tool calls into a human/model readable activity log so a
// model taking over the conversation knows exactly what already happened
// (which files were written, which commands ran, what failed).
function activityFromMessages(msgs) {
  const calls = new Map(); // id -> {name, args}
  const lines = [];
  const parseBlock = (raw) => {
    let o;
    try { o = JSON.parse(raw); } catch (_) { return null; }
    if (!o || typeof o !== 'object') return null;
    const name = o.name || o.tool || (o.function && o.function.name);
    if (!name) return null;
    let args = o.arguments != null ? o.arguments
      : o.input != null ? o.input
      : o.parameters != null ? o.parameters
      : o.function && o.function.arguments;
    if (typeof args === 'string') { try { args = JSON.parse(args); } catch (_) { args = {}; } }
    return { name, args: args && typeof args === 'object' ? args : {} };
  };
  let textSeq = 0;
  for (const m of msgs || []) {
    if (!m || m.role !== 'assistant') continue;
    for (const tc of Array.isArray(m.tool_calls) ? m.tool_calls : []) {
      if (!tc || !tc.function || !tc.function.name) continue;
      let args = tc.function.arguments;
      if (typeof args === 'string') { try { args = JSON.parse(args); } catch (_) { args = {}; } }
      calls.set(tc.id || 'x' + calls.size, { name: tc.function.name, args: args || {} });
    }
    // Text-protocol replies carry the same calls in fenced blocks — a model with
    // no function calling must still leave a usable action trace behind.
    const fence = /```[ \t]*(?:tool|tool_use|json)?[ \t]*\r?\n([\s\S]*?)```/g;
    let fm;
    while ((fm = fence.exec(String(m.content || '')))) {
      const c = parseBlock(fm[1].trim());
      if (!c) continue;
      calls.set('txt_' + (++textSeq), c);
    }
  }
  const reported = new Set();
  const pendingText = []; // text-protocol calls can't carry ids back; match by name
  const push = (c, body) => {
    const a = c.args;
    const target = a.path || a.file || a.command || a.query || a.url || a.name || a.description || '';
    const bad = /^(Error|Tool error)/i.test(String(body || '').trim());
    lines.push(`${c.name}${target ? '(' + oneLine(target, 90) + ')' : ''} → ${bad ? 'ERROR: ' : ''}${oneLine(body, 110)}`);
  };
  for (const [key, c] of calls) if (key.startsWith('txt_')) pendingText.push({ key, name: c.name, args: c.args });
  for (const m of msgs || []) {
    if (!m) continue;
    if (m.role === 'tool') {
      const c = calls.get(m.tool_call_id);
      if (!c) continue;
      reported.add(m.tool_call_id);
      push(c, m.content);
      continue;
    }
    // "TOOL RESULT txt_1_ab12 (Write):\n..." is how the text protocol reports back.
    if (m.role === 'user') {
      const mm = /^TOOL RESULT\s+(\S+)\s+\(([^)]+)\):\n?([\s\S]*)$/.exec(String(m.content || ''));
      if (!mm) continue;
      let c = calls.get(mm[1]);
      let key = mm[1];
      if (!c) {
        // The fenced block the model emitted had no id, so the system invented one.
        // Pair with the oldest un-answered call of the same tool name.
        const i = pendingText.findIndex((p) => p.name === mm[2] && !reported.has(p.key));
        if (i >= 0) { c = { name: pendingText[i].name, args: pendingText[i].args }; key = pendingText[i].key; }
      }
      if (!c) continue;
      reported.add(key);
      push(c, mm[3]);
    }
  }
  // Tool calls whose result never came back (run stopped mid-flight).
  for (const [id, c] of calls) {
    if (reported.has(id)) continue;
    const a = c.args;
    const target = a.path || a.file || a.command || a.name || '';
    lines.push(`${c.name}${target ? '(' + oneLine(target, 90) + ')' : ''} → (no result recorded)`);
  }
  return lines.slice(-12);
}

function todosFromMessages(msgs) {
  let latest = null;
  const take = (name, args) => {
    if (!/^TodoWrite$/.test(name)) return;
    const list = args && Array.isArray(args.todos) ? args.todos : null;
    if (list && list.length) latest = list;
  };
  for (const m of msgs || []) {
    if (!m || m.role !== 'assistant') continue;
    for (const tc of Array.isArray(m.tool_calls) ? m.tool_calls : []) {
      if (!tc || !tc.function || !tc.function.name) continue;
      let args = tc.function.arguments;
      if (typeof args === 'string') { try { args = JSON.parse(args); } catch (_) { args = {}; } }
      take(tc.function.name, args);
    }
    // Text-protocol models keep their todos inside fenced ```tool blocks.
    const fence = /```[ \t]*(?:tool|tool_use|json)?[ \t]*\r?\n([\s\S]*?)```/g;
    let fm;
    while ((fm = fence.exec(String(m.content || '')))) {
      let o;
      try { o = JSON.parse(fm[1].trim()); } catch (_) { continue; }
      if (!o || typeof o !== 'object') continue;
      take(o.name || o.tool || (o.function && o.function.name), o.arguments || o.input || o.parameters || {});
    }
  }
  if (!latest) return [];
  return latest
    .map((t) => (typeof t === 'string' ? t : (t && (t.content || t.title || t.task)) || ''))
    .filter(Boolean)
    .slice(0, 20);
}


// Update the mindmap from a completed (or stopped) run. `messages` is the final
// OpenAI-format message list (or the input list on a stop/abort).
function updateFromRun(cwd, opts) {
  const o = opts || {};
  const msgs = o.messages || [];
  return write(cwd, {
    title: o.title || path.basename(String(cwd)) || 'Untitled project',
    dir: String(cwd),
    goal: o.goal || firstUser(msgs),
    todos: todosFromMessages(msgs),
    activity: o.activity || activityFromMessages(msgs),
    lastExchange: o.lastExchange != null ? o.lastExchange : lastAssistant(msgs),
    files: listFiles(cwd),
  });
}

module.exports = {
  FILENAME, read, write, render, ensureStub, updateFromRun, firstUser, lastAssistant, listFiles,
  activityFromMessages, todosFromMessages,
};
